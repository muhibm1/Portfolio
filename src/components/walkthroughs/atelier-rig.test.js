// Tests the Atelier studio-floor figure and its rig (TG-08, D4): the committed drawing is the
// studio's figure scaled ten times to whole numbers, carries no provenance note, names its parts
// with data-part (never data-go, which the rail buttons use), rests its plates at the first
// station, and every part the rig moves or rings exists in it. Reads the SVG as text.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import * as forbiddenCopy from '../../../scripts/forbidden-copy.mjs';
import { LANE_POS, MOVERS, PART_IDS, POS, SCENES, STEP_PARTS, SWEEP, targetFor, travelMilliseconds, translate } from './atelier-floor.rig.js';

const FIGURE_PATH = path.join(path.dirname(fileURLToPath(import.meta.url)), 'atelier-floor.svg');
const svg = fs.readFileSync(FIGURE_PATH, 'utf8');
const idsInSvg = [...svg.matchAll(/data-part="([^"]+)"/g)].map((match) => match[1]);

describe('the committed Atelier studio floor figure (D4)', () => {
  it('carries no metadata block and no provenance manifest', () => {
    expect(svg).not.toContain('<metadata');
    expect(svg).not.toMatch(/c2pa/i);
    expect(svg).not.toMatch(/generated by|created with|made with/i);
  });

  it('uses the scaled-up view box', () => {
    expect(svg).toMatch(/^<svg [^>]*viewBox="0 0 6800 4300"/);
  });

  it('has no decimal point inside any d, points, cx, cy or r attribute', () => {
    const geometry = [...svg.matchAll(/\s(?:d|points|cx|cy|r)="([^"]*)"/g)].map((match) => match[1]);
    expect(geometry.length).toBeGreaterThan(500);
    expect(geometry.filter((value) => value.includes('.'))).toEqual([]);
  });

  it('holds none of the digits the forbidden-copy scan bans', () => {
    expect(svg).not.toContain('99.9');
    const matchers = forbiddenCopy.buildMatchers([...forbiddenCopy.FORBIDDEN_TERMS]);
    const hits = svg.split('\n').flatMap((line) => forbiddenCopy.termsFoundIn(line, matchers));
    expect(hits).toEqual([]);
  });

  it('has exactly the 16 parts the rig names, each once', () => {
    expect(PART_IDS).toHaveLength(16);
    expect([...idsInSvg].sort()).toEqual([...PART_IDS].sort());
  });

  it('carries no style attribute, and no decimal number except the text-slant coefficients inside a matrix', () => {
    expect(svg).not.toMatch(/\sstyle\s*=/i);
    const withoutMatrices = svg.replace(/matrix\([^)]*\)/g, '');
    expect(withoutMatrices.match(/\d+\.\d+/g) ?? []).toEqual([]);
  });

  it('names its parts with data-part and never with the rail buttons\' data-go or the ring\'s data-on', () => {
    expect(svg).not.toContain('data-go');
    expect(svg).not.toContain('data-on');
  });

  it('wears the fig class the stylesheet targets', () => {
    expect(svg).toMatch(/^<svg [^>]*class="[^"]*\bfig\b/);
  });

  it('rests all three plates at the first station, so the prerendered page is complete without script', () => {
    const [x, y] = POS.intake;
    for (const name of ['plate-1', 'plate-2', 'plate-3']) {
      const tag = svg.match(new RegExp(`<g [^>]*data-part="${name}"[^>]*>`))?.[0];
      expect(tag, name).toContain(`transform="translate(${x} ${y})"`);
    }
  });
});

describe('the rig (D4)', () => {
  it('gives every ringed part and every mover a place in the figure', () => {
    for (const parts of Object.values(STEP_PARTS)) {
      for (const part of parts) expect(idsInSvg).toContain(part);
    }
    for (const mover of MOVERS) expect(idsInSvg).toContain(mover);
  });

  it('has a play scene and a still scene for each of the twelve phase ids', () => {
    const ids = Object.keys(STEP_PARTS);
    expect(ids).toHaveLength(12);
    expect(Object.keys(SCENES).sort()).toEqual([...ids].sort());
    expect(Object.keys(POS).sort()).toEqual([...ids].sort());
    for (const scene of Object.values(SCENES)) {
      expect(typeof scene.play).toBe('function');
      expect(typeof scene.still).toBe('function');
    }
  });

  it('keeps every position and the sweep in whole numbers, in the figure\'s scaled units', () => {
    const numbers = [...Object.values(POS).flat(), ...LANE_POS.flat(), ...SWEEP];
    expect(numbers.filter((value) => !Number.isInteger(value))).toEqual([]);
    expect(LANE_POS).toHaveLength(3);
  });

  it('sends the three plates to their own rails at the lanes and all to the one station elsewhere', () => {
    expect([0, 1, 2].map((i) => targetFor('lanes', i))).toEqual(LANE_POS);
    expect([0, 1, 2].map((i) => targetFor('critics', i))).toEqual([POS.critics, POS.critics, POS.critics]);
  });

  it('makes a longer trip take longer, between the two bounds', () => {
    expect(travelMilliseconds(POS.intake, POS.brief)).toBeLessThan(travelMilliseconds(POS.intake, POS.visitors));
    expect(travelMilliseconds(POS.intake, POS.intake)).toBe(450);
    expect(travelMilliseconds(POS.intake, [100000, 0])).toBe(900);
    expect(translate([3, -4])).toBe('translate(3px, -4px)');
  });
});

// The drawing is placed into the page as raw markup, so it must hold nothing that can run, load or
// link: only shapes, groups, text numerals and inline presentation styles.
describe('the committed Atelier studio floor figure is safe to place as raw markup (D4)', () => {
  it('holds no script, handler, link, embedded content or style element', () => {
    expect(svg).not.toMatch(/<script/i);
    expect(svg).not.toMatch(/\son[a-z]+\s*=/i);
    expect(svg).not.toMatch(/\b(?:xlink:)?href\s*=/i);
    expect(svg).not.toMatch(/<foreignObject/i);
    expect(svg).not.toMatch(/<use[\s>/]/i);
    expect(svg).not.toMatch(/<image[\s>/]/i);
    expect(svg).not.toMatch(/<style/i);
    expect(svg).not.toMatch(/data:/i);
    expect(svg).not.toMatch(/javascript:/i);
  });

  it('refers to nothing outside itself: every url( is a local #id that exists', () => {
    const urls = [...svg.matchAll(/url\(([^)]*)\)/gi)].map((match) => match[1].trim());
    for (const target of urls) {
      expect(target).toMatch(/^#[A-Za-z][\w-]*$/);
      expect(svg).toContain(`id="${target.slice(1)}"`);
    }
  });

  it('declares no external reference in any attribute', () => {
    expect(svg).not.toMatch(/(?:https?:)?\/\/(?!www\.w3\.org\/2000\/svg)/i);
  });
});
